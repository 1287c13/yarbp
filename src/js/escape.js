/**
 * Экранирование для строковой сборки HTML.
 *
 * Почему именно два вида:
 *   - `escText` — для текстового содержимого узла. Кавычки в тексте безвредны,
 *     а вот `&`, `<`, `>` превращают данные в разметку или в сущности.
 *   - `escAttr` — для значения атрибута. Здесь опасны ещё и кавычки: атрибут
 *     закрывается ими, и остаток значения становится новым атрибутом
 *     (`id="x" onmouseover="..."`).
 *
 * Второй аргумент не нужен: любая вставка в HTML-строку идёт через одну из
 * этих функций. Самодельные хелперы (через `textContent`/`innerHTML`,
 * с другим набором символов) — источник расхождений, поэтому в проекте
 * остаётся один модуль.
 */

/** Текст узла: данные не должны становиться тегами или сущностями. */
export function escText(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

/** Значение атрибута (в кавычках): плюс сами кавычки. */
export function escAttr(value) {
  return escText(value)
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * JSON-текст, который кладётся внутрь HTML-разметки (например, в `<data>`).
 *
 * `<` и `&` заменяются на `\u`-последовательности: для `JSON.parse` это тот же
 * символ, а для HTML-парсера — обычный текст. Так JSON не может закрыть
 * объемлющий тег и не портится декодированием сущностей (`&amp;` в значении
 * иначе вернулся бы как `&`).
 */
export function escJsonForHtml(text) {
  return String(text ?? '')
    .replace(/&/g, '\\u0026')
    .replace(/</g, '\\u003c');
}
